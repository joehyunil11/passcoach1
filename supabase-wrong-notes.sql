alter table public.wrong_notes alter column user_id drop not null;
alter table public.wrong_notes alter column question_id drop not null;
alter table public.wrong_notes alter column wrong_count set default 1;
alter table public.wrong_notes alter column last_wrong_at set default now();

do $$
declare
  rec record;
begin
  for rec in
    select c.conname
    from pg_constraint c
    join pg_class t on c.conrelid = t.oid
    join pg_namespace n on n.oid = t.relnamespace
    join unnest(c.conkey) as k(attnum) on true
    join pg_attribute a on a.attrelid = t.oid and a.attnum = k.attnum
    where n.nspname = 'public'
      and t.relname = 'wrong_notes'
      and c.contype = 'f'
      and a.attname = 'question_id'
  loop
    execute format('alter table public.wrong_notes drop constraint if exists %I', rec.conname);
  end loop;
end $$;

