create or replace function public.list_wrong_notes()
returns setof public.wrong_notes
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is not null then
    return query
      select *
      from public.wrong_notes
      where user_id = v_uid
      order by last_wrong_at desc;
  else
    return query
      select *
      from public.wrong_notes
      where user_id is null
      order by last_wrong_at desc;
  end if;
end;
$$;

create or replace function public.upsert_wrong_note(
  p_question_id bigint default null,
  p_subjects text default null,
  p_question_index integer default null,
  p_topic text default null,
  p_note text default null,
  p_selected_answer integer default null,
  p_last_wrong_at timestamptz default null,
  p_increment boolean default true
)
returns public.wrong_notes
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_row public.wrong_notes;
  v_at timestamptz := coalesce(p_last_wrong_at, now());
begin
  if p_question_id is not null then
    select * into v_row
    from public.wrong_notes
    where question_id = p_question_id
      and ((v_uid is null and user_id is null) or user_id = v_uid)
    order by last_wrong_at desc
    limit 1;
  end if;

  if v_row.id is null and p_subjects is not null and p_question_index is not null then
    select * into v_row
    from public.wrong_notes
    where subjects = p_subjects
      and question_index = p_question_index
      and ((v_uid is null and user_id is null) or user_id = v_uid)
    order by last_wrong_at desc
    limit 1;
  end if;

  if v_row.id is not null then
    update public.wrong_notes
    set
      question_id = coalesce(p_question_id, v_row.question_id),
      subjects = coalesce(p_subjects, v_row.subjects),
      question_index = coalesce(p_question_index, v_row.question_index),
      topic = coalesce(p_topic, v_row.topic),
      note = coalesce(p_note, v_row.note),
      selected_answer = coalesce(p_selected_answer, v_row.selected_answer),
      wrong_count = case
        when p_increment then coalesce(v_row.wrong_count, 1) + 1
        else greatest(coalesce(v_row.wrong_count, 1), 1)
      end,
      last_wrong_at = v_at
    where id = v_row.id
    returning * into v_row;
    return v_row;
  end if;

  insert into public.wrong_notes (
    user_id,
    question_id,
    subjects,
    question_index,
    topic,
    note,
    selected_answer,
    wrong_count,
    last_wrong_at
  ) values (
    v_uid,
    p_question_id,
    p_subjects,
    p_question_index,
    p_topic,
    p_note,
    p_selected_answer,
    1,
    v_at
  )
  returning * into v_row;

  return v_row;
end;
$$;

create or replace function public.delete_wrong_note(
  p_question_id bigint default null,
  p_subjects text default null,
  p_question_index integer default null,
  p_all boolean default false
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_count integer := 0;
begin
  if p_all then
    delete from public.wrong_notes
    where (v_uid is null and user_id is null) or user_id = v_uid;
    get diagnostics v_count = row_count;
    return v_count;
  end if;

  if p_question_id is not null then
    delete from public.wrong_notes
    where question_id = p_question_id
      and ((v_uid is null and user_id is null) or user_id = v_uid);
    get diagnostics v_count = row_count;
  end if;

  if v_count = 0 and p_subjects is not null and p_question_index is not null then
    delete from public.wrong_notes
    where subjects = p_subjects
      and question_index = p_question_index
      and ((v_uid is null and user_id is null) or user_id = v_uid);
    get diagnostics v_count = row_count;
  end if;

  return v_count;
end;
$$;

create or replace function public.claim_guest_wrong_notes()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_count integer := 0;
  rec record;
begin
  if v_uid is null then
    return 0;
  end if;

  for rec in
    select *
    from public.wrong_notes
    where user_id is null
  loop
    if exists (
      select 1
      from public.wrong_notes
      where user_id = v_uid
        and (
          (rec.question_id is not null and question_id = rec.question_id)
          or (
            rec.subjects is not null
            and rec.question_index is not null
            and subjects = rec.subjects
            and question_index = rec.question_index
          )
        )
    ) then
      delete from public.wrong_notes where id = rec.id;
    else
      update public.wrong_notes set user_id = v_uid where id = rec.id;
      v_count := v_count + 1;
    end if;
  end loop;

  return v_count;
end;
$$;

