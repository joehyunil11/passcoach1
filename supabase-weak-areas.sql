create or replace function public.list_weakness()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_out jsonb;
begin
  select coalesce(jsonb_agg(item order by ord), '[]'::jsonb)
  into v_out
  from (
    select
      r.id as ord,
      jsonb_build_object(
        'subjects', r.subjects,
        'headline', r.headline,
        'analysis', r.analysis,
        'drill_topic', r.drill_topic,
        'drill_label', r.drill_label,
        'areas', coalesce((
          select jsonb_agg(
            jsonb_build_object(
              'area', a.area,
              'attempted', a.attempted,
              'correct', a.correct,
              'wrong', a.wrong,
              'wrong_rate', a.wrong_rate,
              'sample_topic', a.sample_topic
            )
            order by a.sort_rank, a.wrong desc
          )
          from public.weak_areas a
          where a.subjects = r.subjects
            and (
              (v_uid is null and a.user_id is null)
              or a.user_id = v_uid
            )
        ), '[]'::jsonb)
      ) as item
    from public.weakness_reports r
    where (v_uid is null and r.user_id is null) or r.user_id = v_uid
  ) q;

  return v_out;
end;
$$;

create or replace function public.save_weakness(p_rows jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  rec jsonb;
  area jsonb;
  v_subjects text;
  v_rank integer;
begin
  delete from public.weak_areas
  where (v_uid is null and user_id is null) or user_id = v_uid;
  delete from public.weakness_reports
  where (v_uid is null and user_id is null) or user_id = v_uid;

  for rec in
    select value from jsonb_array_elements(coalesce(p_rows, '[]'::jsonb))
  loop
    v_subjects := nullif(trim(both from coalesce(rec->>'subjects', rec->>'subjectId', '')), '');
    if v_subjects is null then
      continue;
    end if;

    insert into public.weakness_reports (
      user_id, subjects, headline, analysis, drill_topic, drill_label, updated_at
    ) values (
      v_uid,
      v_subjects,
      nullif(trim(both from coalesce(rec->>'headline', '')), ''),
      nullif(trim(both from coalesce(rec->>'analysis', '')), ''),
      nullif(trim(both from coalesce(rec->>'drill_topic', rec->>'drillTopic', '')), ''),
      nullif(trim(both from coalesce(rec->>'drill_label', rec->>'drillLabel', '')), ''),
      now()
    );

    v_rank := 0;
    for area in
      select value from jsonb_array_elements(coalesce(rec->'areas', '[]'::jsonb))
    loop
      if nullif(trim(both from coalesce(area->>'area', area->>'name', '')), '') is null then
        continue;
      end if;
      v_rank := v_rank + 1;
      insert into public.weak_areas (
        user_id, subjects, area, attempted, correct, wrong, wrong_rate, sample_topic, sort_rank, updated_at
      ) values (
        v_uid,
        v_subjects,
        nullif(trim(both from coalesce(area->>'area', area->>'name', '')), ''),
        greatest(coalesce((area->>'attempted')::integer, 0), 0),
        greatest(coalesce((area->>'correct')::integer, 0), 0),
        greatest(coalesce((area->>'wrong')::integer, 0), 0),
        greatest(coalesce((area->>'wrong_rate')::integer, (area->>'wrongRate')::integer, 0), 0),
        nullif(trim(both from coalesce(area->>'sample_topic', area->>'sampleTopic', '')), ''),
        v_rank,
        now()
      );
    end loop;
  end loop;

  return public.list_weakness();
end;
$$;

create or replace function public.claim_guest_weakness()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_own integer := 0;
  v_guest integer := 0;
begin
  if v_uid is null then
    return 0;
  end if;

  select count(*) into v_own from public.weakness_reports where user_id = v_uid;
  select count(*) into v_guest from public.weakness_reports where user_id is null;

  if v_guest = 0 then
    return 0;
  end if;

  if v_own > 0 then
    delete from public.weak_areas where user_id is null;
    delete from public.weakness_reports where user_id is null;
    return 0;
  end if;

  update public.weak_areas set user_id = v_uid, updated_at = now() where user_id is null;
  update public.weakness_reports set user_id = v_uid, updated_at = now() where user_id is null;
  return v_guest;
end;
$$;

