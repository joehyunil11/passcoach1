create table if not exists public.weakness_reports (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  subjects text not null,
  headline text,
  analysis text,
  drill_topic text,
  drill_label text,
  updated_at timestamptz not null default now()
);

create table if not exists public.weak_areas (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  subjects text not null,
  area text not null,
  attempted integer not null default 0,
  correct integer not null default 0,
  wrong integer not null default 0,
  wrong_rate integer not null default 0,
  sample_topic text,
  sort_rank integer not null default 1,
  updated_at timestamptz not null default now()
);

alter table public.weakness_reports alter column user_id drop not null;
alter table public.weak_areas alter column user_id drop not null;

create unique index if not exists weakness_reports_owner_subject_uidx
  on public.weakness_reports (
    coalesce(user_id, '00000000-0000-0000-0000-000000000000'::uuid),
    subjects
  );

create unique index if not exists weak_areas_owner_subject_area_uidx
  on public.weak_areas (
    coalesce(user_id, '00000000-0000-0000-0000-000000000000'::uuid),
    subjects,
    area
  );

